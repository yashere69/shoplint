"""Regenerate results/before-after.md from the two sample catalogs.

python tools/before_after.py
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

from shoplint.probe import probe, summary
from shoplint.rules import audit, builtin_packs, load_pack
from shoplint.shopify import read_csv

ROOT = Path(__file__).resolve().parent.parent


def stats(name: str) -> tuple[Counter, dict]:
    products = read_csv(ROOT / "examples" / name)
    findings = audit(products, [load_pack(n) for n in builtin_packs()])
    return Counter(f.level for f in findings), summary(probe(products))


def main() -> None:
    (b_lv, b_pr), (a_lv, a_pr) = stats("indigo-loom.csv"), stats("indigo-loom-fixed.csv")
    lines = [
        "# Before and after: Indigo Loom sample catalog",
        "",
        "Generated by `python tools/before_after.py`. Indigo Loom is a fictional store; the "
        "catalog was written to contain common Shopify export problems.",
        "",
        "| | Before | After |",
        "|---|---|---|",
        f"| Errors | {b_lv['error']} | {a_lv['error']} |",
        f"| Warnings | {b_lv['warning']} | {a_lv['warning']} |",
        f"| Buyer questions answerable from structured data | {b_pr['answerable']}/"
        f"{b_pr['questions']} ({b_pr['answerable_pct']}%) | {a_pr['answerable']}/"
        f"{a_pr['questions']} ({a_pr['answerable_pct']}%) |",
        "",
        "| Question | Structured before | Structured after |",
        "|---|---|---|",
    ]
    for q, c in b_pr["by_question"].items():
        after = a_pr["by_question"][q]
        total = sum(c.values())
        lines.append(f"| {q} | {c['structured']}/{total} | {after['structured']}/{total} |")
    out = ROOT / "results" / "before-after.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out.read_text())


if __name__ == "__main__":
    main()
